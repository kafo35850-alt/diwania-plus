STOP=set("""في من على أن لا إلى و ما عن هذا مع التي كل هذه أو هو كان الذي ذلك بعد لم بين ان كانت يا حتى قبل قد هي هم هن انا أنا انت أنت نحن انتم إن إذا اذا لو لكن ثم أي اي كما عند منذ لقد هل ليس كيف أين متى لماذا هنا هناك الى ولا وما فقد وقد لن إلا الا غير بل أما اما مثل حيث فيه فيها منه منها عليه عليها له لها لهم به بها التى الذين اللي ايش وش يعني""".split())
def norm(w):
    w=re.sub(r'[ً-ْـ]','',w)
    w=re.sub('[أإآ]','ا',w).replace('ى','ي').replace('ة','ه').replace('ؤ','و').replace('ئ','ي')
    if w.startswith('ال') and len(w)>4: w=w[2:]
    return w
words=top_n_list('ar',60000)+DIAL.split()
ok=re.compile(r'^[ء-ي]{2,14}$')
seen={};order=[]
for w in words:
    if not ok.match(w) or w in STOP: continue
    n=norm(w)
    if len(n)<2 or n in seen: continue
    seen[n]=w if not w.startswith('ال') else w[2:]
    order.append(n)
S=set(order)
keep=[]
for n in order:
    # drop clitic-prefixed duplicates: وكتاب، بالبيت، للبيت، فالكتاب، كالبيت
    m=re.match(r'^(وال|بال|فال|كال|لل|و|ف|ب|ل|ك)(.+)$',n)
    if m:
        rest=m.group(2); rest2=rest[2:] if rest.startswith('ال') else rest
        if rest in S or rest2 in S: continue
    keep.append(n)
vocab=[seen[n] for n in keep]
print(len(order),len(keep))
json.dump({'norm':keep,'disp':vocab},open('vocab.json','w'),ensure_ascii=False)
