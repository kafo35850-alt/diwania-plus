// Bundles everything in public/ into the Worker (worker/src/static.generated.js), so the site deploys
// as a single Worker with no separate asset upload.  node scripts/build-static.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pub = join(root, 'public');
const TYPES = { html: 'text/html; charset=utf-8', js: 'text/javascript; charset=utf-8', css: 'text/css; charset=utf-8', svg: 'image/svg+xml', png: 'image/png', txt: 'text/plain; charset=utf-8' };
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name !== '_headers') files.push(relative(pub, p).split('\\').join('/'));
  }
})(pub);
let imports = '', table = '';
files.sort().forEach((f, i) => {
  const ext = f.split('.').pop();
  if (!TYPES[ext]) throw new Error('unsupported file type: ' + f);
  if (ext === 'png') {
    // Binary files are imported as Data modules; text files are inlined as strings.
    imports += 'import f' + i + " from '../../public/" + f + "';\n";
    table += "  '/" + f + "': [f" + i + ", '" + TYPES[ext] + "'],\n";
  } else {
    table += "  '/" + f + "': [" + JSON.stringify(readFileSync(join(pub, f), 'utf8')).replace(/<\/script/gi, '<\\/script') + ", '" + TYPES[ext] + "'],\n";
  }
});
writeFileSync(join(root, 'worker/src/static.generated.js'),
  '// AUTO-GENERATED by scripts/build-static.mjs — do not edit.\n' + imports + '\nexport const STATIC = {\n' + table + '};\n');
console.log('bundled', files.length, 'public files');
