// Extracts the multiplayer room hub + game engine scripts from the game files so the
// Worker (Durable Object) runs exactly the same rules as the game pages.
//   node scripts/build-room-engines.mjs
// Re-run it whenever games/dakhil.html, mafia.html, qaftah.html or chancellor.html change.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// game slug -> { scripts to load in order, expression for the engine object }
const GAMES = {
  dakhil: { scripts: ['hub.js', 'kit/lobby.js', 'games/dakhil/words.js', 'games/dakhil/engine.js'], engine: 'self.MG.dakhil' },
  mafia: { scripts: ['hub.js', 'engine.js'], engine: 'self.MafiaEngine' },
  qaftah: { scripts: ['hub.js', 'qf/engine.js'], engine: 'self.QFEngine' },
  chancellor: { scripts: ['hub.js', 'sh/engine.js'], engine: 'self.SHEngine' },
  harf: { scripts: ['hub.js', 'kit/lobby.js', 'games/harf/data.js', 'games/harf/engine.js'], engine: 'self.MG.harf' },
  qaddirha: { scripts: ['hub.js', 'kit/lobby.js', 'games/qaddirha/data.js', 'games/qaddirha/engine.js'], engine: 'self.MG.qaddirha' }
};

function scriptBlock(html, name, file) {
  const marker = '<script>/* ' + name + ' */';
  const start = html.indexOf(marker);
  if (start === -1) throw new Error(file + ': script block "' + name + '" not found');
  const end = html.indexOf('</script>', start);
  return html.slice(start + '<script>'.length, end);
}

let out = '// AUTO-GENERATED by scripts/build-room-engines.mjs from games/*.html — do not edit by hand.\n' +
  '/* eslint-disable */\n\n';
const names = [];
for (const [slug, spec] of Object.entries(GAMES)) {
  const file = join(root, 'games', slug + '.html');
  const html = readFileSync(file, 'utf8');
  const body = spec.scripts.map((n) => scriptBlock(html, n, file)).join('\n');
  for (const banned of ['document.', 'localStorage', 'window.']) {
    if (body.includes(banned)) console.warn('warning: ' + slug + ' engine mentions ' + banned);
  }
  out += 'function load_' + slug + '() {\n  const self = {};\n' + body + '\n  return { Hub: self.MafiaHub, E: ' + spec.engine + ' };\n}\n\n';
  names.push(slug);
}
out += 'export const ROOM_ENGINES = {\n' + names.map((n) => '  ' + n + ': load_' + n).join(',\n') + '\n};\n';
writeFileSync(join(root, 'worker/src/rooms/engines.generated.js'), out);
console.log('wrote worker/src/rooms/engines.generated.js for: ' + names.join(', '));
